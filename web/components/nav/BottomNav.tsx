const ICONS: Record<string, (props: IconProps) => React.JSX.Element> = {
  "/dashboard": HomeIcon,
  "/resume": DocumentIcon,
  "/searches": SearchIcon,
  "/jobs": BriefcaseIcon,
  "/settings": GearIcon,
};

export function BottomNav() {
  const pathname = usePathname();

  return (
    <nav
      className="fixed inset-x-0 bottom-0 z-30 flex border-t border-brand-ink-100 bg-white pb-[env(safe-area-inset-bottom)] md:hidden"
      aria-label="Primary"
    >
      {NAV_ITEMS.map((item) => {
        const active = isActive(pathname, item.href);
        const Icon = ICONS[item.href] ?? HomeIcon;
        return (
          <Link
            key={item.href}
            href={item.href}
            aria-current={active ? "page" : undefined}
            className={cn(
              "flex flex-1 flex-col items-center justify-center gap-0.5 py-2 text-xs font-medium transition-colors",
              "min-h-[56px]",
              active ? "text-brand-orange-700" : "text-brand-ink-500 hover:text-brand-ink-700"
            )}
          >
            <Icon className="h-5 w-5" />
            <span>{item.label}</span>
          </Link>
        );
      })}
    </nav>
  );
}
